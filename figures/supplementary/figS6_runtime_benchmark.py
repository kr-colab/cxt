"""
Figure S6: Wall-clock runtime comparison between cxt, SMC++, and Singer.

Loads pre-computed benchmark timing data and plots runtime scaling curves.

NOTE: The benchmark data (JSONL files) should be generated by running the
full benchmark experiments in revision/figure_benchmark/experiment.ipynb.
This script handles only the plotting.
"""

import argparse
import json
import os

import numpy as np

from figures.paths import BENCHMARK_JSONL
import matplotlib.pyplot as plt
import pandas as pd


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", default="figures/output/supplementary")
    parser.add_argument("--cache-dir", default="figures/output/supplementary/cache/figS6")
    parser.add_argument("--benchmark-data", default=BENCHMARK_JSONL,
                        help="Path to cxt_benchmark_runtime_blocks.jsonl")
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)

    if args.benchmark_data and os.path.exists(args.benchmark_data):
        records = []
        with open(args.benchmark_data) as f:
            for line in f:
                records.append(json.loads(line))
        df = pd.DataFrame(records)

        fig, ax = plt.subplots(figsize=(8, 5))
        if "num_pairs" in df.columns and "total_seconds" in df.columns:
            ax.plot(df["num_pairs"], df["total_seconds"], "o-", color="dodgerblue", label="cxt")
        ax.set_xlabel("Number of inferred pairs")
        ax.set_ylabel("Wall-clock time (seconds)")
        ax.set_title("Runtime scaling", loc="left")
        ax.legend()
        ax.grid(alpha=0.3)
        plt.tight_layout()

        out = os.path.join(args.output_dir, "figS6_runtime_benchmark.png")
        fig.savefig(out, dpi=300)
        print(f"Saved {out}")
        plt.close(fig)
    else:
        print("No benchmark data provided. Use --benchmark-data to supply the JSONL file.")
        print("Expected format: one JSON object per line with 'num_pairs' and 'total_seconds' fields.")


if __name__ == "__main__":
    main()
